public class Calculator 
{
    //adds 2 numbers
    public int addInt(int a, int b)
    {
        return a+b;
    }
    
    //adds 3 numbers
    public int add3Int(int a, int b, int c)
    {
        return a+b+c;
    }

    //adds 2 doubles
    public double addDouble(double a, double b)
    {
        return a+b;
    }

    //concatenate two strings
    public String addString(String a, String b)
    {
        return a+b;
    }

}
